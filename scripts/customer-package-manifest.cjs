#!/usr/bin/env node
'use strict';

/**
 * M13.3 — generates the authoritative V1 customer-package tree.
 *
 * Run:  node scripts/customer-package-manifest.cjs > docs/customer-package.md
 *
 * It reports the tree of files that WILL ship, exactly as
 * `scripts/dist-file-set.cjs` defines them, plus the statistics a release
 * reviewer needs: file and folder totals, empty files, empty folders, size, and
 * an extension breakdown.
 *
 * It deliberately reports the INTENDED package — the tracked V1 set — including
 * files that are still untracked and therefore do not ship yet. That is the
 * point of the manifest: it is the checklist that must reach zero before the
 * release gate goes green.
 */

const fs = require('node:fs');
const path = require('node:path');

const { shippedFiles, intendedFiles, REQUIRED_FILES } = require('./dist-file-set.cjs');

const ROOT = path.resolve(__dirname, '..');

/**
 * Everything the V1 package is intended to contain: tracked + untracked, minus
 * `.distignore` exclusions. Files that are not yet tracked are still V1 content
 * — the manifest exists to make that gap explicit and countable.
 */
const intended = intendedFiles();

function extensionOf(rel) {
  const base = path.basename(rel);
  if (base.startsWith('.') && !base.slice(1).includes('.')) return base; // .env, .gitignore
  const ext = path.extname(base);
  return ext === '' ? '(none)' : ext;
}

function buildTree(paths) {
  const root = { name: 'oxyide-forge/', path: '', children: new Map() };
  for (const rel of paths) {
    const parts = rel.split('/');
    let node = root;
    let prefix = '';
    for (let i = 0; i < parts.length; i += 1) {
      const name = parts[i];
      prefix = prefix === '' ? name : `${prefix}/${name}`;
      const isLeaf = i === parts.length - 1;
      if (!node.children.has(name)) {
        node.children.set(name, { name, path: prefix, children: new Map(), isDir: !isLeaf });
      }
      const child = node.children.get(name);
      if (isLeaf) child.isDir = false;
      node = child;
    }
  }
  return root;
}

/**
 * Renders the tree, annotating each leaf with whether it is currently tracked.
 *
 * The annotation is computed from the node's real path, never from the rendered
 * glyphs: stripping box-drawing characters loses the directory context, so a
 * tracked file like docs/adr/001-authentication.md would be marked by bare name
 * and mislabelled.
 */
function render(node, prefix = '', trackedSet = new Set(), lines = []) {
  const entries = [...node.children.values()].sort((a, b) => {
    if (a.isDir !== b.isDir) return a.isDir ? -1 : 1;
    return a.name.localeCompare(b.name);
  });
  entries.forEach((child, i) => {
    const last = i === entries.length - 1;
    const tag = child.isDir ? '/' : trackedSet.has(child.path) ? '' : '   *(untracked)*';
    lines.push(`${prefix}${last ? '└── ' : '├── '}${child.name}${tag}`);
    if (child.isDir) render(child, `${prefix}${last ? '    ' : '│   '}`, trackedSet, lines);
  });
  return lines;
}

function main() {
  const trackedSet = new Set(shippedFiles());
  const tree = buildTree(intended);

  // --- statistics ---------------------------------------------------------
  const extensions = new Map();
  let totalBytes = 0;
  let emptyFiles = 0;
  const emptyFileList = [];

  for (const rel of intended) {
    const abs = path.join(ROOT, rel);
    let size = 0;
    try {
      const stat = fs.statSync(abs);
      size = stat.isFile() ? stat.size : 0;
      if (stat.isFile() && size === 0) {
        emptyFiles += 1;
        emptyFileList.push(rel);
      }
    } catch {
      size = 0;
    }
    totalBytes += size;
    const ext = extensionOf(rel);
    extensions.set(ext, (extensions.get(ext) || 0) + 1);
  }

  const allFolders = new Set();
  for (const rel of intended) {
    const parts = rel.split('/');
    for (let i = 1; i < parts.length; i += 1) allFolders.add(parts.slice(0, i).join('/'));
  }

  // A folder is "empty" if no intended file lives beneath it.
  const emptyFolders = [...allFolders].filter(
    (dir) => !intended.some((f) => f.startsWith(`${dir}/`)),
  );

  const byExt = [...extensions.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
  const human = (n) => `${(n / 1024).toFixed(1)} KiB`;
  const notTracked = intended.filter((f) => !trackedSet.has(f));

  const out = [];
  out.push('# Oxyide Forge V1 — Customer Package Manifest');
  out.push('');
  out.push('> Generated by `scripts/customer-package-manifest.cjs` from the single');
  out.push('> definition in `scripts/dist-file-set.cjs`. Do not hand-edit.');
  out.push('>');
  out.push('> This is the **intended** package. Files marked *(untracked)* are');
  out.push('> required for V1 but are not yet part of the repository, so they do not');
  out.push('> ship. The required-file gate (`npm run release:check`) passes only on');
  out.push('> its own required set; anything else in this gap reaches customers');
  out.push('> only after it is committed.');
  out.push('');
  out.push('## Summary');
  out.push('');
  out.push('| Metric | Value |');
  out.push('|---|---|');
  out.push(`| Total files in package | **${intended.length}** |`);
  out.push(`| Total folders in package | **${allFolders.size}** |`);
  out.push(`| Files shipping today | ${intended.length - notTracked.length} |`);
  out.push(`| Files blocked (untracked) | ${notTracked.length} |`);
  out.push(`| Empty files | **${emptyFiles}** |`);
  out.push(`| Empty folders | **${emptyFolders.length}** |`);
  out.push(`| Total size | ${human(totalBytes)} |`);
  out.push(`| Distinct extensions | ${byExt.length} |`);
  out.push('');

  out.push('## Breakdown by extension');
  out.push('');
  out.push('| Extension | Files |');
  out.push('|---|---:|');
  for (const [ext, count] of byExt) out.push(`| \`${ext}\` | ${count} |`);
  out.push('');

  out.push('## Empty files');
  out.push('');
  if (emptyFiles === 0) {
    out.push('None. Every file in the package has content.');
  } else {
    out.push('| File | Note |');
    out.push('|---|---|');
    for (const f of emptyFileList) out.push(`| \`${f}\` | zero bytes — review |`);
  }
  out.push('');

  out.push('## Empty folders');
  out.push('');
  if (emptyFolders.length === 0) {
    out.push('None.');
  } else {
    for (const f of emptyFolders) out.push(`- \`${f}/\``);
  }
  out.push('');

  out.push('## Blocked files (untracked, must ship)');
  out.push('');
  out.push('| File | Reason it is required |');
  out.push('|---|---|');
  for (const f of notTracked) {
    let why = 'V1 content';
    if (REQUIRED_FILES.includes(f)) why = 'required customer file';
    else if (f.startsWith('prisma/migrations/')) why = 'migration history';
    out.push(`| \`${f}\` | ${why} |`);
  }
  out.push('');

  out.push('## Package tree');
  out.push('');
  out.push('```text');
  out.push('oxyide-forge/');
  for (const line of render(tree, '', trackedSet)) out.push(line);
  out.push('```');
  out.push('');

  process.stdout.write(out.join('\n'));
}

main();
